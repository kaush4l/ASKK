// Compile the companion into one executable with the app embedded.
//   bun --bun next build && bun scripts/build-companion.js [--target bun-darwin-arm64]
// Writes companion/assets.gen.js (URL path -> embedded file), then
// dist/askk. Run the result from any folder to browse that folder.

import { Glob } from "bun"
import { resolve } from "node:path"

const here = resolve(import.meta.dir, "..")
const out = resolve(here, "out")
const files = [...new Glob("**/*").scanSync({ cwd: out, onlyFiles: true, dot: false })].sort()
if (!files.length) throw new Error("out/ is empty. Run `bun --bun next build` first.")

const lines = ["// Generated by scripts/build-companion.js — do not edit.", ""]
files.forEach((file, i) => lines.push(`import a${i} from "../out/${file}" with { type: "file" }`))
lines.push("", "export default {")
files.forEach((file, i) => lines.push(`  ${JSON.stringify(`/${file}`)}: a${i},`))
lines.push("}", "")
await Bun.write(resolve(here, "companion/assets.gen.js"), lines.join("\n"))

const target = Bun.argv.includes("--target") ? Bun.argv[Bun.argv.indexOf("--target") + 1] : null
const cmd = ["bun", "build", "--compile", "--minify", "companion/server.js", "companion/team-worker.js", "--outfile", "dist/askk", ...(target ? ["--target", target] : [])]
const proc = Bun.spawn(cmd, { cwd: here, stdout: "inherit", stderr: "inherit" })
if ((await proc.exited) !== 0) process.exit(1)
console.log(`Embedded ${files.length} files → dist/askk`)
